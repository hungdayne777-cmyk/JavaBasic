    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        //  Kiểm tra các ô Text rỗng
        if (txtMaSV.getText().trim().isEmpty() || txtHoTen.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ Mã SV và Họ tên!");
            return; // Dừng hàm ngay lập tức
        }

        //  Kiểm tra Ngày sinh rỗng 
        if (dtcNgaySinh.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn Ngày sinh!");
            return; // Dừng hàm
        }

        //Kiểm tra ComboBox Khoa
        if (cboKhoa.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn Khoa!");
            return; // Dừng hàm
        }

        // Nếu tất cả đều hợp lệ mới tạo đối tượng và chèn vào CSDL
        SinhVien sv = Gan_Du_lieu();

        if (sinhVienDao.insert(sv)) {
            JOptionPane.showMessageDialog(this, "Thêm sinh viên thành công!");
            Khoi_Tao_Table();
            btnLamMoiActionPerformed(null);
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại! Mã sinh viên có thể đã tồn tại.");
        }
    }//GEN-LAST:event_btnThemActionPerformed

