    private void Khoi_Tao_Table() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("MaSV");
        model.addColumn("HoTen");
        model.addColumn("NgaySinh");
        model.addColumn("GioiTinh");
        model.addColumn("DiaChi");
        model.addColumn("MaKhoa");

        JTable table = new JTable(model);
        JScrollPane scrollPane = new JScrollPane(table);
        model.setRowCount(0);

        model = (DefaultTableModel) tblSinhVien.getModel();

        model.setColumnIdentifiers(new Object[]{
            "Mã SV", "Họ tên", "Ngày sinh", "Giới tính", "Địa chỉ", "Mã khoa"
        });

        model.setRowCount(0);

        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd/MM/yyyy");

        SinhVienDao sinhVienDao = new SinhVienDao();
        List<SinhVien> list = sinhVienDao.findAll();
        for (SinhVien sv : list) {
            String strNgaySinh = (sv.getNgaySinh() != null) ? sdf.format(sv.getNgaySinh()) : "";
            String strGioiTinh = sv.isGioiTinh() ? "Nam" : "Nữ";

            model.addRow(new Object[]{
                sv.getMaSV(),
                sv.getHoTen(),
                strNgaySinh,
                strGioiTinh,
                sv.getDiaChi(),
                sv.getMaKhoa()
            });
        }
    }

    private SinhVien Gan_Du_lieu() {
        String maSV = txtMaSV.getText().trim();
        String hoTen = txtHoTen.getText().trim();

        // Kiểm tra ngày tháng
        Date ngaySinh = (dtcNgaySinh.getDate() != null) ? dtcNgaySinh.getDate() : new Date();

        boolean gioiTinh = radNam.isSelected();
        String diaChi = txtDiaChi.getText().trim();

        // Kiểm tra ComboBox
        String maKhoa = "";
        if (cboKhoa.getSelectedItem() != null) {
            if (cboKhoa.getSelectedItem() instanceof Khoa) {
                Khoa k = (Khoa) cboKhoa.getSelectedItem();
                maKhoa = k.getMaKhoa();
            } else {
                maKhoa = cboKhoa.getSelectedItem().toString();
            }
        }
        return new SinhVien(maSV, hoTen, ngaySinh, gioiTinh, diaChi, maKhoa);
    }

    private void Chon_Khoa(String maKhoa) {
        for (int i = 0; i < cboKhoa.getItemCount(); i++) {
            Object item = cboKhoa.getItemAt(i);

            if (item instanceof Khoa) {
                Khoa k = (Khoa) item;
                if (k.getMaKhoa().equalsIgnoreCase(maKhoa)) {
                    cboKhoa.setSelectedIndex(i);
                    return;
                }
            } else if (item.toString().equalsIgnoreCase(maKhoa)) {
                cboKhoa.setSelectedIndex(i);
                return;
            }
        }
    }

