    private void btnSuaDKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaDKActionPerformed
        int selectedRow = tblDangKy.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn đăng ký cần sửa từ danh sách!");
            return;
        }

        // 2. Kiểm tra các ô điểm rỗng
        if (txtDiemQT.getText().trim().isEmpty() || txtDiemThi.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ điểm Quá Trình và điểm Thi!");
            return;
        }

        // 3. Kiểm tra Ngày đăng ký
        if (dtcNgayDK.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn Ngày Đăng Ký!");
            return;
        }

        // 4. Kiểm tra ComboBox
        if (cboTenSV.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn Sinh Viên!");
            return;
        }
        if (cboTenMH.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn Môn Học!");
            return;
        }

        DangKyView dk = Gan_Du_LieuDK();
        if (dk == null) {
            return;
        }

        if (dangKyDao.update(dk)) {
            JOptionPane.showMessageDialog(this, "Cập nhật thành công!");
            Khoi_Tao_TableDK();
            btnLamMoiActionPerformed(null);
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại! Vui lòng kiểm tra lại thông tin.");
        }
    }//GEN-LAST:event_btnSuaDKActionPerformed

