    private DangKyView Gan_Du_LieuDK() {
        try {

            double diemqt = Double.parseDouble(txtDiemQT.getText().trim());
            double diemthi = Double.parseDouble(txtDiemThi.getText().trim());
            if (diemqt < 0 || diemqt > 10 || diemthi < 0 || diemthi > 10) {
                JOptionPane.showMessageDialog(this, "Điểm phải nằm trong khoảng từ 0 đến 10");
                return null;
            }

            double diemtk = (diemqt * 0.4) + (diemthi * 0.6);
            diemtk = Math.round(diemtk * 10.0) / 10.0;
            txtDiemTK.setText(String.valueOf(diemtk));

            Date ngayDK = (dtcNgayDK.getDate() != null) ? dtcNgayDK.getDate() : new Date();

            String maSV = "";
            String tenSV = "";
            if (cboTenSV.getSelectedItem() != null) {
                if (cboTenSV.getSelectedItem() instanceof SinhVien) {
                    SinhVien sv = (SinhVien) cboTenSV.getSelectedItem();
                    maSV = sv.getMaSV();
                    tenSV = sv.getHoTen();
                } else {
                    String strSV = cboTenSV.getSelectedItem().toString();
                    String[] parts = strSV.split(" - ");
                    maSV = parts[0].trim();
                    tenSV = (parts.length > 1) ? parts[1].trim() : "";
                }
            }

            String maMH = "";
            String tenMH = "";
            if (cboTenMH.getSelectedItem() != null) {
                if (cboTenMH.getSelectedItem() instanceof MonHoc) {
                    MonHoc mh = (MonHoc) cboTenMH.getSelectedItem();
                    maMH = mh.getMaMH();
                    tenMH = mh.getTenMH();
                } else {
                    String strMH = cboTenMH.getSelectedItem().toString();
                    String[] parts = strMH.split(" - ");
                    maMH = parts[0].trim();
                    tenMH = (parts.length > 1) ? parts[1].trim() : "";
                }
            }

            return new DangKyView(maSV, maMH, ngayDK, diemqt, diemthi, diemtk, tenSV, tenMH);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đúng định dạng số cho Điểm quá trình và Điểm thi!");
            return null;
        }
    }

